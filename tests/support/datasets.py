def write_project(root: Path, layout: Mapping[str, str]) -> Dict[str, Path]:
    """Materialise a multi-file layout under *root*.

    Args:
        root: Directory to write into, typically pytest's ``tmp_path``.
        layout: Maps POSIX-style relative paths to file contents. Parent
            directories are created automatically.

    Returns:
        The same keys mapped to the absolute :class:`~pathlib.Path` written,
        so a test can address a file without re-joining paths by hand.
    """
    written: Dict[str, Path] = {}

    for relative, content in layout.items():
        path = root.joinpath(*relative.split("/"))
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written[relative] = path

    return written
